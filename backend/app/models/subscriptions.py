"""Recurring subscriptions."""
import enum

from sqlalchemy import (
    Boolean,
    Column,
    Date,
    DateTime,
    Enum,
    ForeignKey,
    Index,
    Integer,
    Numeric,
    String,
    Text,
    UniqueConstraint,
)
from sqlalchemy.orm import relationship

from backend.app.core.database import Base
from backend.app.models.base import TenantMixin, TimestampMixin, UUIDPrimaryKeyMixin


class SubscriptionStatus(str, enum.Enum):
    DRAFT = "draft"
    PENDING_ACTIVATION = "pending_activation"
    ACTIVE = "active"
    TRIALING = "trialing"
    PAST_DUE = "past_due"  # renewal invoice overdue
    PAUSED = "paused"
    CANCELLED = "cancelled"
    TRIAL_EXPIRED = "trial_expired"  # trial ended without converting
    EXPIRED = "expired"  # subscription term ended


class Subscription(UUIDPrimaryKeyMixin, TenantMixin, TimestampMixin, Base):
    __tablename__ = "subscriptions"
    __table_args__ = (
        UniqueConstraint("organization_id", "subscription_number", name="uq_subscription_number_per_org"),
        Index("ix_subscriptions_org_status", "organization_id", "status"),
    )

    subscription_number = Column(String(24), nullable=False)
    customer_id = Column(String(36), ForeignKey("customers.id", ondelete="RESTRICT"), nullable=False, index=True)
    plan_id = Column(String(36), ForeignKey("plans.id", ondelete="RESTRICT"), nullable=False, index=True)
    quantity = Column(Integer, nullable=False, default=1)
    status = Column(
        Enum(SubscriptionStatus, name="subscription_status"), nullable=False, default=SubscriptionStatus.ACTIVE, index=True
    )

    billing_frequency = Column(String(32), nullable=False, default="monthly")
    currency = Column(String(3), nullable=False, default="INR")
    pricing_model = Column(String(32), nullable=False, default="flat")

    # Agreed commercial terms snapshot (preserving exact pricing when created)
    unit_price = Column(Numeric(14, 2), nullable=False, default=0)
    subtotal = Column(Numeric(14, 2), nullable=False, default=0)
    discount_amount = Column(Numeric(14, 2), nullable=False, default=0)
    tax_amount = Column(Numeric(14, 2), nullable=False, default=0)
    total_amount = Column(Numeric(14, 2), nullable=False, default=0)

    start_date = Column(Date, nullable=False)
    trial_start = Column(Date, nullable=True)
    trial_end = Column(Date, nullable=True)
    current_period_start = Column(Date, nullable=False)
    current_period_end = Column(Date, nullable=False)
    # Date the next renewal invoice will be generated by the scheduler (normally = current_period_end).
    next_billing_date = Column(Date, nullable=True, index=True)
    auto_renewal = Column(Boolean, nullable=False, default=True)
    cancel_at_period_end = Column(Boolean, nullable=False, default=False)
    cancelled_at = Column(DateTime(timezone=True), nullable=True)
    cancellation_reason = Column(Text, nullable=True)
    paused_at = Column(DateTime(timezone=True), nullable=True)
    ended_at = Column(DateTime(timezone=True), nullable=True)
    notes = Column(Text, nullable=True)
    created_by_id = Column(String(36), ForeignKey("users.id", ondelete="SET NULL"), nullable=True)
    updated_by_id = Column(String(36), ForeignKey("users.id", ondelete="SET NULL"), nullable=True)

    customer = relationship("Customer")
    plan = relationship("Plan")
    subscription_items = relationship(
        "SubscriptionItem", back_populates="subscription", cascade="all, delete-orphan"
    )
    trial_period = relationship(
        "TrialPeriod", back_populates="subscription", uselist=False, cascade="all, delete-orphan"
    )
